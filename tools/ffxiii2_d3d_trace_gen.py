#!/usr/bin/env python3
"""ffxiii2-nx (2026-11-03): writes app/src/ffxiii2/ffxiii2_d3d_trace_hooks.inc, one pass-through hook per function of
FFXIII-2's Direct3D area (0x82840000-0x82960000, the function starts of app/generated/renut_init.cpp), for the PC
trace that pairs Renut's hooks with this game's functions (src/ffxiii2/ffxiii2_d3d_trace.cpp; feedingfrenzy-nx's
method, docs/zumasrevenge-notes.md). Addresses already hooked elsewhere are left out.

  python tools/ffxiii2_d3d_trace_gen.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LO, HI = 0x82840000, 0x82960000
SKIP = {0x828510C8}  # the graphics interrupt handler (src/ffxiii2/ffxiii2_irq.cpp)

init = open(os.path.join(ROOT, 'app', 'generated', 'renut_init.cpp')).read()
starts = sorted(int(m, 16) for m in re.findall(r'\{ 0x([0-9A-F]{8}), sub_', init))
funcs = [a for a in starts if LO <= a < HI and a not in SKIP]
out = ['// Generated by tools/ffxiii2_d3d_trace_gen.py: %d functions of 0x%08X-0x%08X. Do not edit.' % (len(funcs), LO, HI),
       '#define FFXIII2_D3D_TRACE_COUNT %d' % len(funcs)]
out.append('static const uint32_t kTraceAddr[FFXIII2_D3D_TRACE_COUNT] = {')
out += ['  0x%08X,' % a for a in funcs]
out.append('};')
for i, a in enumerate(funcs):
    out.append('REX_EXTERN(__imp__sub_%08X);' % a)
    out.append('REX_HOOK_RAW(sub_%08X) { ::ffxiii2::d3dtrace::Note(%d, ctx); __imp__sub_%08X(ctx, base); }' % (a, i, a))
path = os.path.join(ROOT, 'app', 'src', 'ffxiii2', 'ffxiii2_d3d_trace_hooks.inc')
open(path, 'w', newline='\n').write('\n'.join(out) + '\n')
print('%d hooks -> %s' % (len(funcs), path))
